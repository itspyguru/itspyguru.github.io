// em/en dashes and smart quotes show up in prose — fold them onto ASCII shapes
const FOLD = { '—': '-', '–': '-', '’': "'", '‘': "'", '“': '"', '”': '"', '…': '...' }

export function glyph(ch) {
  const up = ch.toUpperCase()
  return G[up] || G[FOLD[up]] || G[' ']
}

export function foldText(s) {
  return String(s).replace(/[—–’‘“”…]/g, (c) => FOLD[c]).toUpperCase()
}
